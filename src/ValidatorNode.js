const { ethers } = require("ethers");

/**
 * ValidatorNode
 * Simulates a decentralized TEE (Trusted Execution Environment) or zkML / AVS validator
 * on Base / Ethereum. Audits task outputs independently and commits cryptographic attestations
 * to the ValidationRegistry.
 */
class ValidatorNode {
  /**
   * @param {Object} options
   * @param {string|ethers.Wallet} [options.privateKey] - Private key or Wallet instance
   * @param {ethers.Provider} [options.provider] - Ethers provider
   * @param {string} [options.nodeName] - Name of the validator node
   * @param {string} [options.validatorType] - Type of verification ("TEE-SGX", "zkML", "AVS-Consensus")
   */
  constructor(options = {}) {
    const {
      privateKey,
      provider,
      nodeName = "zkSepolia-IntelSGX-Enclave-01",
      validatorType = "TEE-SGX"
    } = options;

    this.provider = provider || (privateKey && privateKey.provider ? privateKey.provider : null);

    if (privateKey && typeof privateKey.sendTransaction === "function") {
      this.wallet = privateKey;
    } else if (typeof privateKey === "string" && privateKey.startsWith("0x")) {
      this.wallet = new ethers.Wallet(privateKey, this.provider);
    } else {
      this.wallet = ethers.Wallet.createRandom(this.provider);
    }

    this.address = this.wallet.address;
    this.nodeName = nodeName;
    this.validatorType = validatorType;
  }

  /**
   * Connects this validator to a provider
   * @param {ethers.Provider} provider 
   */
  connect(provider) {
    this.provider = provider;
    this.wallet = this.wallet.connect(provider);
    return this;
  }

  /**
   * Independently audits and verifies an agent's task execution report.
   * Simulates TEE enclave remote attestation or zkML inference proof verification.
   * 
   * @param {Object} taskReport - The report generated by AutonomousAgent.executeTask
   * @returns {Object} - Audit findings, score (0-100), proofHash, and tag
   */
  auditTaskExecution(taskReport) {
    if (!taskReport || !taskReport.executionData) {
      throw new Error("Invalid task report: executionData is required");
    }

    const { executionData, taskHash } = taskReport;

    // 1. Verify cryptographic hash integrity of execution data
    const computedHash = ethers.keccak256(ethers.toUtf8Bytes(JSON.stringify(executionData)));
    const hashMatches = computedHash.toLowerCase() === taskHash.toLowerCase();

    // 2. Perform independent mathematical re-calculation
    const { spotPriceUsd, reserves, tvlUsd } = executionData.metrics;
    const computedTvl = (reserves.token0.amount * spotPriceUsd) + reserves.token1.amount;
    const tvlDiff = Math.abs(computedTvl - tvlUsd);
    const mathConsistent = tvlDiff < 1.0; // Within rounding tolerance

    // 3. Determine verification score
    let verificationScore = 100;
    if (!hashMatches) {
      verificationScore = 0;
    } else if (!mathConsistent) {
      verificationScore = 50;
    }

    // 4. Generate enclave attestation / zk proof payload
    const attestationPayload = {
      validator: this.address,
      nodeName: this.nodeName,
      validatorType: this.validatorType,
      verifiedTaskHash: taskHash,
      hashIntegrityPassed: hashMatches,
      mathematicalModelPassed: mathConsistent,
      enclaveQuote: ethers.hexlify(ethers.randomBytes(32)),
      timestamp: Math.floor(Date.now() / 1000)
    };

    const proofHash = ethers.keccak256(ethers.toUtf8Bytes(JSON.stringify(attestationPayload)));
    const tag = this.validatorType === "TEE-SGX" ? "TEE-ATTESTED" : "zkML-VERIFIED";
    const proofUri = `ipfs://bafybeiatestationquote${Date.now()}/proof.json`;

    return {
      isValid: verificationScore >= 80,
      verificationScore,
      proofHash,
      proofUri,
      tag,
      attestationPayload
    };
  }

  /**
   * Submits a formal validation response to the ValidationRegistry contract.
   * 
   * @param {ethers.Contract} validationContract - ValidationRegistry contract instance
   * @param {string} validationId - The unique bytes32 ID of the validation request
   * @param {Object} auditResult - Output from auditTaskExecution
   * @returns {Promise<Object>} - Transaction receipt and response confirmation
   */
  async submitValidationResponse(validationContract, validationId, auditResult) {
    const contractWithSigner = validationContract.connect(this.wallet);

    const safeTag = ethers.encodeBytes32String(auditResult.tag.slice(0, 31));

    const tx = await contractWithSigner.validationResponse(
      validationId,
      auditResult.verificationScore,
      auditResult.proofUri,
      auditResult.proofHash,
      safeTag
    );

    const receipt = await tx.wait();

    return {
      txHash: tx.hash,
      receipt,
      validationId,
      score: auditResult.verificationScore,
      tag: auditResult.tag,
      proofHash: auditResult.proofHash,
      proofUri: auditResult.proofUri
    };
  }
}

module.exports = { ValidatorNode };
ValidatorNode.default = ValidatorNode;
